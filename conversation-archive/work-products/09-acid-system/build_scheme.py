def set_run_font(run, size: float | None = None, bold: bool | None = None, color: str | None = None):
    run.font.name = FONT
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), FONT)
    run._element.get_or_add_rPr().rFonts.set(qn("w:ascii"), FONT)
    run._element.get_or_add_rPr().rFonts.set(qn("w:hAnsi"), FONT)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color is not None:
        run.font.color.rgb = RGBColor.from_string(color)


def replace_runs(paragraph, old: str, new: str):
    for run in paragraph.runs:
        if old in run.text:
            run.text = run.text.replace(old, new)


def keep_next(paragraph):
    paragraph.paragraph_format.keep_with_next = True
    paragraph.paragraph_format.keep_together = True


def add_heading(doc: Document, text: str, level: int = 1, page_break: bool = False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(6 if level == 1 else 2)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.page_break_before = page_break
    keep_next(p)
    r = p.add_run(text)
    set_run_font(r, 12, True)
    return p


def add_para(doc: Document, text: str, indent: bool = True, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    r = p.add_run(text)
    set_run_font(r, 12, False)
    return p


